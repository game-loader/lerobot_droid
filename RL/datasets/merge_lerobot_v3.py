"""Atomic materialization of canonical LeRobot v3 RL datasets.

The iterative RL loop has two kinds of input dataset: an imitation-learning
dataset without RL fields and a rollout dataset which already contains the
canonical sparse transition fields.  LeRobot's in-place writer is deliberately
used only against a sibling staging directory; source datasets are never
modified and all derived indices/statistics are regenerated by the writer.
"""

from __future__ import annotations

import hashlib
import json
import os
import uuid
from collections.abc import Mapping
from dataclasses import dataclass
from pathlib import Path
from typing import Any

import numpy as np

from lerobot.datasets.lerobot_dataset import LeRobotDataset
from RL.adapters.lerobot_v3 import SUCCESS_MIN_FINAL_LIFT_HEIGHT, terminal_success

_RL_FIELDS = ("next.reward", "next.done", "next.truncated")
_REQUIRED_LABEL_FIELDS = {
    "true_grasp_ever",
    "clear_table_ever",
    "final_lift_height_m",
    "final_table_contacts",
    "final_hand_contacts",
}
_AUTO_FEATURES = {"timestamp", "frame_index", "episode_index", "index", "task_index"}


@dataclass(frozen=True)
class LeRobotV3MergeSource:
    """A read-only v3 source and its episode-level collection summary."""

    dataset_root: Path | str
    repo_id: str
    summary_path: Path | str

    def __post_init__(self) -> None:
        root = Path(self.dataset_root)
        summary = Path(self.summary_path)
        if not root.is_dir():
            raise ValueError(f"dataset_root does not exist or is not a directory: {root}")
        if not summary.is_file():
            raise ValueError(f"summary_path does not exist or is not a file: {summary}")
        if not isinstance(self.repo_id, str) or not self.repo_id.strip():
            raise ValueError("repo_id must be a nonempty string")


def _load_summary(source: LeRobotV3MergeSource) -> dict[str, Any]:
    try:
        payload = json.loads(Path(source.summary_path).read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as exc:
        raise ValueError(f"failed to read summary {source.summary_path}: {exc}") from exc
    if not isinstance(payload, dict):
        raise ValueError(f"summary must contain an object: {source.summary_path}")
    records = payload.get("episodes")
    if not isinstance(records, list):
        raise ValueError(f"summary episodes must be a list: {source.summary_path}")
    return payload


def _as_int(value: Any, *, field: str, context: str) -> int:
    if isinstance(value, bool) or not isinstance(value, (int, np.integer)):
        raise ValueError(f"{context}.{field} must be an integer, got {value!r}")
    return int(value)


def _as_bool(value: Any, *, field: str, context: str) -> bool:
    if not isinstance(value, (bool, np.bool_)):
        raise ValueError(f"{context}.{field} must be a bool, got {value!r}")
    return bool(value)


def _summary_records(
    source: LeRobotV3MergeSource, dataset: LeRobotDataset, summary: Mapping[str, Any]
) -> list[dict[str, Any]]:
    records = summary.get("episodes")
    if not isinstance(records, list):
        raise ValueError(f"summary episodes must be a list for {source.repo_id}")
    if len(records) != dataset.num_episodes:
        raise ValueError(
            f"summary episode count disagrees for {source.repo_id}: "
            f"summary={len(records)}, dataset={dataset.num_episodes}"
        )
    episodes_saved = summary.get("episodes_saved")
    if (
        episodes_saved is not None
        and _as_int(episodes_saved, field="episodes_saved", context="summary") != dataset.num_episodes
    ):
        raise ValueError(f"summary episodes_saved disagrees for {source.repo_id}")
    normalized: list[dict[str, Any]] = []
    for expected, raw in enumerate(records):
        if not isinstance(raw, Mapping):
            raise ValueError(f"summary episode {expected} must be a mapping")
        record = dict(raw)
        index = _as_int(record.get("episode_index"), field="episode_index", context=f"episode[{expected}]")
        if index != expected:
            raise ValueError(
                f"summary episode indices must be contiguous for {source.repo_id}: "
                f"expected={expected}, got={index}"
            )
        length = _as_int(
            record.get("frames", record.get("episode_length")), field="frames", context=f"episode[{expected}]"
        )
        metadata = dataset.meta.episodes[expected]
        actual_length = _as_int(metadata["length"], field="length", context=f"dataset episode[{expected}]")
        if length != actual_length:
            raise ValueError(
                f"summary frame count disagrees for {source.repo_id} episode {expected}: "
                f"summary={length}, dataset={actual_length}"
            )
        for field in _REQUIRED_LABEL_FIELDS:
            if field not in record:
                raise ValueError(f"summary episode {expected} is missing {field}")
        normalized.append(record)
    return normalized


def _source_task(dataset: LeRobotDataset, summary: Mapping[str, Any], records: list[dict[str, Any]]) -> str:
    summary_task = summary.get("task")
    tasks = [str(value) for value in dataset.meta.tasks.index.tolist()]
    if not tasks:
        raise ValueError("source dataset has no task")
    if len(set(tasks)) != 1:
        raise ValueError(f"source dataset must contain exactly one task, got {tasks}")
    task = tasks[0]
    if summary_task is not None and summary_task != task:
        raise ValueError(f"summary task {summary_task!r} disagrees with dataset task {task!r}")
    # ``source_task`` is provenance, not the task label currently stored in
    # the dataset.  A previous canonical merge may have changed the dataset
    # task while retaining each episode's original task name (for example,
    # ``grasp and lift randomized charger`` -> ``moya_charger_grasp``).
    # Validate its shape, but do not require provenance to equal the current
    # canonical task.  The summary-level task and dataset metadata above are
    # the authoritative labels for this source.
    for index, record in enumerate(records):
        # Missing provenance is valid for legacy summaries.  Once the field is
        # present, however, keep its type and value strict; an explicit null
        # must not silently turn into "unknown" provenance.
        if "source_task" in record:
            source_task = record["source_task"]
            if not isinstance(source_task, str) or not source_task.strip():
                raise ValueError(f"episode {index} source_task must be a nonempty string")
    return task


def _schema(dataset: LeRobotDataset, *, source_name: str) -> dict[str, dict[str, Any]]:
    features = dataset.features
    required = ("observation.state", "action")
    for key in required:
        if key not in features:
            raise ValueError(f"{source_name} dataset is missing {key!r}")
        if features[key].get("dtype") != "float32":
            raise ValueError(f"{source_name} {key} must have dtype float32")
        if not isinstance(features[key].get("shape"), (tuple, list)):
            raise ValueError(f"{source_name} {key} has invalid shape")
    user_features = {key: dict(value) for key, value in features.items() if key not in _AUTO_FEATURES}
    camera_keys = [key for key, value in user_features.items() if value.get("dtype") in ("image", "video")]
    if camera_keys:
        raise ValueError(f"image/video features are not supported by this state-only merger: {camera_keys}")
    return user_features


def _compare_base_rollout_schema(base: dict[str, dict[str, Any]], rollout: dict[str, dict[str, Any]]) -> None:
    for key in ("observation.state", "action"):
        if key not in rollout:
            raise ValueError(f"rollout dataset is missing {key!r}")
        for property_name in ("dtype", "shape"):
            base_value = base[key].get(property_name)
            rollout_value = rollout[key].get(property_name)
            if property_name == "shape":
                base_value = tuple(base_value or ())
                rollout_value = tuple(rollout_value or ())
            if rollout_value != base_value:
                raise ValueError(f"rollout {key} {property_name} differs from base schema")
        rollout_names = rollout[key].get("names")
        if rollout_names is not None and rollout_names != base[key].get("names"):
            raise ValueError(f"rollout {key} names differ from base schema")
    unsupported_base = set(base).difference({"observation.state", "action", *_RL_FIELDS})
    if unsupported_base:
        raise ValueError(f"base has unsupported features: {sorted(unsupported_base)}")
    unexpected = set(rollout).difference({*base, *_RL_FIELDS})
    if unexpected:
        raise ValueError(f"rollout has unsupported features: {sorted(unexpected)}")
    present = [key for key in _RL_FIELDS if key in rollout]
    if len(present) != len(_RL_FIELDS):
        missing = sorted(set(_RL_FIELDS).difference(present))
        raise ValueError(f"rollout must contain canonical RL fields; missing={missing}")
    for key, dtype in (("next.reward", "float32"), ("next.done", "bool"), ("next.truncated", "bool")):
        if key in rollout and (
            rollout[key].get("dtype") != dtype or tuple(rollout[key].get("shape", ())) != (1,)
        ):
            raise ValueError(f"rollout {key} must have dtype {dtype} and shape [1]")


def _raw_episode(dataset: LeRobotDataset, row: Mapping[str, Any]) -> dict[str, list[Any]]:
    start = _as_int(row["dataset_from_index"], field="dataset_from_index", context="episode")
    stop = _as_int(row["dataset_to_index"], field="dataset_to_index", context="episode")
    raw = dataset.hf_dataset[start:stop]
    if not isinstance(raw, Mapping):
        raise ValueError("dataset slice must be a mapping")
    return dict(raw)


def _validate_rollout_episode(
    raw: Mapping[str, Any], record: Mapping[str, Any], *, episode_index: int
) -> tuple[np.ndarray, np.ndarray, np.ndarray]:
    expected_success = terminal_success(record)
    recorded_success = record.get("success")
    if not isinstance(recorded_success, (bool, np.bool_)):
        raise ValueError(f"rollout summary episode {episode_index} is missing boolean success")
    if bool(recorded_success) != expected_success:
        raise ValueError(
            f"rollout summary success disagrees with acceptance fields for episode {episode_index}"
        )
    for key, dtype in (("next.reward", np.float32), ("next.done", np.bool_), ("next.truncated", np.bool_)):
        if key not in raw:
            raise ValueError(f"rollout episode {episode_index} is missing {key}")
        values = np.asarray(raw[key], dtype=dtype)
        if values.ndim == 1:
            values = values.reshape(-1, 1)
        if values.ndim != 2 or values.shape[1] != 1:
            raise ValueError(f"rollout {key} must have shape [frames, 1]")
        if key == "next.reward" and (not np.isfinite(values).all() or not np.isin(values, [0.0, 1.0]).all()):
            raise ValueError("rollout next.reward must be finite and binary")
        if values.shape[0] == 0:
            raise ValueError(f"rollout {key} has no rows")
        if key == "next.done" and not bool(values[-1, 0]):
            raise ValueError("rollout final frame must be done")
        if key == "next.done" and bool(values[:-1].any()):
            raise ValueError("rollout next.done may only be true on final frame")
        if key == "next.truncated" and bool(
            np.any(values & ~np.asarray(raw["next.done"], dtype=np.bool_).reshape(-1, 1))
        ):
            raise ValueError("rollout next.truncated may only be true on done frame")
    reward: np.ndarray = np.asarray(raw["next.reward"], dtype=np.float32).reshape(-1, 1)
    done: np.ndarray = np.asarray(raw["next.done"], dtype=np.bool_).reshape(-1, 1)
    truncated: np.ndarray = np.asarray(raw["next.truncated"], dtype=np.bool_).reshape(-1, 1)
    if float(reward[-1, 0]) != float(expected_success):
        raise ValueError(f"rollout terminal reward disagrees with summary for episode {episode_index}")
    if bool(truncated[-1, 0]) == expected_success:
        raise ValueError(f"rollout terminal truncation disagrees with summary for episode {episode_index}")
    if np.any(reward[:-1] != 0.0):
        raise ValueError("rollout non-terminal rewards must be zero")
    return reward, done, truncated


def _legacy_fields(length: int, success: bool) -> tuple[np.ndarray, np.ndarray, np.ndarray]:
    reward: np.ndarray = np.zeros((length, 1), dtype=np.float32)
    done: np.ndarray = np.zeros((length, 1), dtype=np.bool_)
    truncated: np.ndarray = np.zeros((length, 1), dtype=np.bool_)
    done[-1, 0] = True
    reward[-1, 0] = float(success)
    truncated[-1, 0] = not success
    return reward, done, truncated


def _digest_tree(root: Path) -> str:
    digest = hashlib.sha256()
    for path in sorted(root.rglob("*")):
        if path.is_file():
            digest.update(str(path.relative_to(root)).encode())
            digest.update(path.read_bytes())
    return digest.hexdigest()


def _digest_file(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        while chunk := handle.read(1024 * 1024):
            digest.update(chunk)
    return digest.hexdigest()


def _reject_output_inside_sources(output: Path, sources: tuple[Path, Path]) -> None:
    """Prevent staging from mutating either source dataset tree."""

    resolved_output = output.resolve(strict=False)
    for source in sources:
        resolved_source = source.resolve(strict=True)
        if resolved_output == resolved_source or resolved_output.is_relative_to(resolved_source):
            raise ValueError(
                "merge output must be outside every source dataset root: "
                f"output={resolved_output} source={resolved_source}"
            )


def _write_json(path: Path, payload: Mapping[str, Any]) -> None:
    path.write_text(json.dumps(payload, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    with path.open("rb") as handle:
        os.fsync(handle.fileno())


def merge_lerobot_v3_datasets(
    output_dir: Path | str,
    *,
    output_repo_id: str,
    base: LeRobotV3MergeSource,
    rollout: LeRobotV3MergeSource,
    canonical_task: str | None = None,
) -> Path:
    """Merge two sources into a new canonical v3 dataset atomically."""

    output = Path(output_dir)
    if output.exists():
        raise FileExistsError(f"output path already exists: {output}")
    if not isinstance(output_repo_id, str) or not output_repo_id.strip():
        raise ValueError("output_repo_id must be a nonempty string")

    _reject_output_inside_sources(
        output,
        (Path(base.dataset_root), Path(rollout.dataset_root)),
    )

    base_summary = _load_summary(base)
    rollout_summary = _load_summary(rollout)
    base_ds = LeRobotDataset(base.repo_id, root=Path(base.dataset_root), download_videos=False)
    rollout_ds = LeRobotDataset(rollout.repo_id, root=Path(rollout.dataset_root), download_videos=False)
    base_records = _summary_records(base, base_ds, base_summary)
    rollout_records = _summary_records(rollout, rollout_ds, rollout_summary)
    base_task = _source_task(base_ds, base_summary, base_records)
    rollout_task = _source_task(rollout_ds, rollout_summary, rollout_records)
    if canonical_task is None:
        if base_task != rollout_task:
            raise ValueError(
                "source tasks differ; provide canonical_task explicitly: "
                f"base={base_task!r}, rollout={rollout_task!r}"
            )
        canonical_task = base_task
    if not isinstance(canonical_task, str) or not canonical_task.strip():
        raise ValueError("canonical_task must be a nonempty string")

    base_schema = _schema(base_ds, source_name="base")
    rollout_schema = _schema(rollout_ds, source_name="rollout")
    _compare_base_rollout_schema(base_schema, rollout_schema)
    base_rl_fields = [key for key in _RL_FIELDS if key in base_schema]
    if base_rl_fields and len(base_rl_fields) != len(_RL_FIELDS):
        missing = sorted(set(_RL_FIELDS).difference(base_rl_fields))
        raise ValueError(f"base canonical RL fields are incomplete; missing={missing}")
    if base_ds.fps != rollout_ds.fps:
        raise ValueError(f"source fps differ: base={base_ds.fps}, rollout={rollout_ds.fps}")
    if base_ds.meta.robot_type is None:
        raise ValueError("base dataset robot_type is required")
    if rollout_ds.meta.robot_type not in (None, base_ds.meta.robot_type):
        raise ValueError(
            "rollout robot_type differs from base: "
            f"base={base_ds.meta.robot_type!r}, rollout={rollout_ds.meta.robot_type!r}"
        )
    if rollout_summary.get("complete") is not True:
        raise ValueError("rollout canonical summary must have complete=true")

    canonical_features = dict(base_schema)
    canonical_features.update(
        {
            "next.reward": {"dtype": "float32", "shape": (1,), "names": None},
            "next.done": {"dtype": "bool", "shape": (1,), "names": None},
            "next.truncated": {"dtype": "bool", "shape": (1,), "names": None},
        }
    )
    output.parent.mkdir(parents=True, exist_ok=True)
    staging = output.parent / f"{output.name}.incomplete-{uuid.uuid4().hex}"
    dataset_root = staging / "dataset"
    source_digests = {
        "base": _digest_tree(Path(base.dataset_root)),
        "rollout": _digest_tree(Path(rollout.dataset_root)),
        "base_summary": _digest_file(Path(base.summary_path)),
        "rollout_summary": _digest_file(Path(rollout.summary_path)),
    }
    all_records: list[dict[str, Any]] = []
    initial_summary: dict[str, Any] = {
        "complete": False,
        "repo_id": output_repo_id,
        "task": canonical_task,
        "fps": int(base_ds.fps),
        "episodes_saved": 0,
        "success_count": 0,
        "failure_count": 0,
        "lineage": {
            "operation": "canonical_v3_merge",
            "sources": [
                {
                    "name": "base",
                    "repo_id": base.repo_id,
                    "dataset_root": str(Path(base.dataset_root)),
                    "summary_path": str(Path(base.summary_path)),
                    "dataset_sha256": source_digests["base"],
                    "summary_sha256": source_digests["base_summary"],
                    "source_task": base_task,
                },
                {
                    "name": "rollout",
                    "repo_id": rollout.repo_id,
                    "dataset_root": str(Path(rollout.dataset_root)),
                    "summary_path": str(Path(rollout.summary_path)),
                    "dataset_sha256": source_digests["rollout"],
                    "summary_sha256": source_digests["rollout_summary"],
                    "source_task": rollout_task,
                },
            ],
            "success_threshold_m": SUCCESS_MIN_FINAL_LIFT_HEIGHT,
        },
        "episodes": all_records,
    }
    try:
        staging.mkdir(parents=False, exist_ok=False)
        _write_json(staging / "collection_summary.json", initial_summary)
        dataset = LeRobotDataset.create(
            repo_id=output_repo_id,
            fps=int(base_ds.fps),
            robot_type=base_ds.meta.robot_type,
            features=canonical_features,
            root=dataset_root,
            use_videos=False,
        )
        output_index = 0
        for source_name, source_ds, records in (
            ("base", base_ds, base_records),
            ("rollout", rollout_ds, rollout_records),
        ):
            for source_index, record in enumerate(records):
                raw = _raw_episode(source_ds, source_ds.meta.episodes[source_index])
                success = terminal_success(record)
                recorded_success = record.get("success")
                if recorded_success is not None and not isinstance(recorded_success, (bool, np.bool_)):
                    raise ValueError(f"{source_name} summary episode {source_index} success must be a bool")
                if recorded_success is not None and bool(recorded_success) != success:
                    raise ValueError(
                        f"{source_name} summary success disagrees with acceptance fields "
                        f"for episode {source_index}"
                    )
                if source_name == "base" and not base_rl_fields:
                    reward, done, truncated = _legacy_fields(int(record["frames"]), success)
                else:
                    reward, done, truncated = _validate_rollout_episode(
                        raw, record, episode_index=source_index
                    )
                length = int(record["frames"])
                for frame_index in range(length):
                    frame = {
                        "task": canonical_task,
                        "observation.state": np.asarray(
                            raw["observation.state"][frame_index], dtype=np.float32
                        ).reshape(tuple(base_schema["observation.state"]["shape"])),
                        "action": np.asarray(raw["action"][frame_index], dtype=np.float32).reshape(
                            tuple(base_schema["action"]["shape"])
                        ),
                        "next.reward": reward[frame_index],
                        "next.done": done[frame_index],
                        "next.truncated": truncated[frame_index],
                    }
                    dataset.add_frame(frame)
                dataset.save_episode()
                output_record = dict(record)
                output_record.update(
                    {
                        "episode_index": output_index,
                        "source": source_name,
                        "source_repo_id": source_ds.repo_id,
                        "source_episode_index": source_index,
                        "source_task": base_task if source_name == "base" else rollout_task,
                        "frames": length,
                        "success": bool(success),
                    }
                )
                all_records.append(output_record)
                output_index += 1
        dataset.finalize()
        final_summary = dict(initial_summary)
        final_summary["complete"] = True
        final_summary["episodes_saved"] = len(all_records)
        final_summary["success_count"] = sum(bool(record["success"]) for record in all_records)
        final_summary["failure_count"] = len(all_records) - final_summary["success_count"]
        final_summary["episodes"] = all_records
        _write_json(staging / "collection_summary.json", final_summary)
        _write_json(staging / "lineage.json", final_summary["lineage"])
        _validate_output(dataset_root, output_repo_id, final_summary)
        if _digest_tree(Path(base.dataset_root)) != source_digests["base"]:
            raise RuntimeError("base dataset changed during merge")
        if _digest_tree(Path(rollout.dataset_root)) != source_digests["rollout"]:
            raise RuntimeError("rollout dataset changed during merge")
        if _digest_file(Path(base.summary_path)) != source_digests["base_summary"]:
            raise RuntimeError("base summary changed during merge")
        if _digest_file(Path(rollout.summary_path)) != source_digests["rollout_summary"]:
            raise RuntimeError("rollout summary changed during merge")
        os.replace(staging, output)
        try:
            directory_fd = os.open(output.parent, os.O_RDONLY)
            try:
                os.fsync(directory_fd)
            finally:
                os.close(directory_fd)
        except OSError:
            pass
    except BaseException:
        raise
    return output


def _validate_output(dataset_root: Path, repo_id: str, summary: Mapping[str, Any]) -> None:
    dataset = LeRobotDataset(repo_id, root=dataset_root, download_videos=False)
    if not summary.get("complete"):
        raise ValueError("output summary is not complete")
    if dataset.num_episodes != int(summary["episodes_saved"]):
        raise ValueError("output episode count disagrees with summary")
    if dataset.num_frames != sum(int(row["frames"]) for row in summary["episodes"]):
        raise ValueError("output frame count disagrees with summary")
    if set(dataset.meta.tasks.index) != {summary["task"]}:
        raise ValueError("output task metadata disagrees with summary")
    raw = dataset.hf_dataset[: dataset.num_frames]
    indexes = np.asarray(raw["index"], dtype=np.int64)
    if not np.array_equal(indexes, np.arange(dataset.num_frames)):
        raise ValueError("output global frame indices are not contiguous")
    for key in _RL_FIELDS:
        if key not in dataset.features:
            raise ValueError(f"output is missing canonical field {key}")
    cursor = 0
    for episode_index, (metadata, record) in enumerate(
        zip(dataset.meta.episodes, summary["episodes"], strict=True)
    ):
        length = int(record["frames"])
        start = int(metadata["dataset_from_index"])
        stop = int(metadata["dataset_to_index"])
        if int(metadata["episode_index"]) != episode_index or start != cursor or stop != cursor + length:
            raise ValueError(f"output episode metadata is not contiguous at episode {episode_index}")
        episode_indices = np.asarray(raw["episode_index"][start:stop], dtype=np.int64)
        frame_indices = np.asarray(raw["frame_index"][start:stop], dtype=np.int64)
        if not np.array_equal(episode_indices, np.full(length, episode_index)):
            raise ValueError(f"output episode_index column disagrees at episode {episode_index}")
        if not np.array_equal(frame_indices, np.arange(length)):
            raise ValueError(f"output frame_index column disagrees at episode {episode_index}")
        reward = np.asarray(raw["next.reward"][start:stop], dtype=np.float32).reshape(-1)
        done = np.asarray(raw["next.done"][start:stop], dtype=np.bool_).reshape(-1)
        truncated = np.asarray(raw["next.truncated"][start:stop], dtype=np.bool_).reshape(-1)
        success = terminal_success(record)
        if np.any(reward[:-1] != 0.0) or float(reward[-1]) != float(success):
            raise ValueError(f"output sparse reward disagrees at episode {episode_index}")
        if bool(done[:-1].any()) or not bool(done[-1]):
            raise ValueError(f"output done flags disagree at episode {episode_index}")
        if bool(truncated[:-1].any()) or bool(truncated[-1]) == success:
            raise ValueError(f"output truncated flags disagree at episode {episode_index}")
        cursor = stop
    if cursor != dataset.num_frames:
        raise ValueError("output episode bounds do not cover all frames")
    success_count = sum(terminal_success(record) for record in summary["episodes"])
    if success_count != int(summary["success_count"]):
        raise ValueError("output success count disagrees with summary")
    for key in ("observation.state", "action", *_RL_FIELDS):
        count = int(np.asarray(dataset.meta.stats[key]["count"]).reshape(-1)[0])
        if count != dataset.num_frames:
            raise ValueError(f"output {key} statistics count disagrees")


